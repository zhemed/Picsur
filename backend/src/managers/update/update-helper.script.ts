/**
 * The script the "updater helper" container runs.
 *
 * Why a helper container at all?
 *   The API can not stop the container it runs in: the moment the old container
 *   stops, the process that would start the replacement is gone. The helper is
 *   a tiny container from the *old* (known good) image, its only job is:
 *
 *     1. rename the old container out of the way
 *     2. stop it (this kills the API, not the helper)
 *     3. rename + start the new container
 *     4. probe the new container until it answers /api/info
 *     5. remove the old container (success) or start it again (rollback)
 *
 * It is plain node with the builtins only, and talks to the docker socket over
 * http. It is passed to the container as `node -e <script>`, the job data comes
 * in through the PICSUR_UPDATE_JOB environment variable.
 *
 * The helper container is created with `restart: on-failure`, and every step
 * below is written to be re-runnable: if the helper is killed (OOM, `docker
 * kill`, daemon restart) in the middle of the swap, docker starts it again and
 * the second run finishes the job - either by completing the update or by
 * rolling back to the old container. Nothing here may assume it runs once.
 */
export const UpdateHelperScript = [
  "const http = require('http');",
  "const os = require('os');",
  "const job = JSON.parse(process.env.PICSUR_UPDATE_JOB);",
  'const log = (...args) => console.log(new Date().toISOString(), ...args);',
  'function api(method, path, body) {',
  '  return new Promise((resolve, reject) => {',
  '    const payload = body === undefined ? undefined : Buffer.from(JSON.stringify(body));',
  '    const req = http.request({',
  '      socketPath: job.socketPath,',
  '      path: path,',
  '      method: method,',
  '      headers: Object.assign(',
  "        { Host: 'docker', 'Content-Type': 'application/json' },",
  "        payload ? { 'Content-Length': String(payload.length) } : {},",
  '      ),',
  '      timeout: job.apiTimeoutMs || 120000,',
  '    }, (res) => {',
  '      const chunks = [];',
  "      res.on('data', (c) => chunks.push(c));",
  "      res.on('end', () => {",
  "        const text = Buffer.concat(chunks).toString('utf8');",
  '        // 304 = "already in the desired state" for start/stop, treat it as ok',
  '        if ((res.statusCode >= 200 && res.statusCode < 300) || res.statusCode === 304) {',
  '          try { resolve(text.trim() === "" ? undefined : JSON.parse(text)); }',
  '          catch (e) { resolve(text); }',
  '        } else {',
  "          reject(new Error(method + ' ' + path + ' -> ' + res.statusCode + ' ' + text.slice(0, 300)));",
  '        }',
  '      });',
  '    });',
  "    req.on('timeout', () => req.destroy(new Error('timeout ' + method + ' ' + path)));",
  "    req.on('error', reject);",
  '    if (payload) req.write(payload);',
  '    req.end();',
  '  });',
  '}',
  'const sleep = (ms) => new Promise((r) => setTimeout(r, ms));',
  'const stage = (msg) => log(msg);',
  'async function inspect(id) {',
  '  try { return await api("GET", "/containers/" + id + "/json"); }',
  '  catch (e) { return null; }',
  '}',
  'const nameOf = (c) => (c && c.Name ? String(c.Name).replace(/^\\//, "") : null);',
  'async function dumpLogs(id, label) {',
  '  try {',
  '    const text = await api("GET", "/containers/" + id + "/logs?stdout=1&stderr=1&tail=30");',
  '    if (typeof text === "string" && text.trim() !== "") {',
  "      log('--- last log lines of ' + label + ' ---');",
  '      console.log(text.replace(/[\\u0000-\\u0008\\u000b-\\u001f]/g, ""));',
  '    }',
  '  } catch (e) {',
  "    log('could not read the logs of ' + label + ': ' + e.message);",
  '  }',
  '}',
  'async function probeOnce() {',
  '  const execId = (await api("POST", "/containers/" + job.newId + "/exec", {',
  '    AttachStdout: false, AttachStderr: false, Cmd: job.probeCmd,',
  '  })).Id;',
  '  await api("POST", "/exec/" + execId + "/start", { Detach: true, Tty: false });',
  '  const singleDeadline = Date.now() + 30000;',
  '  while (Date.now() < singleDeadline) {',
  '    const info = await api("GET", "/exec/" + execId + "/json");',
  '    if (!info.Running) return info.ExitCode === 0;',
  '    await sleep(1000);',
  '  }',
  '  return false;',
  '}',
  'async function probeNew() {',
  '  const deadline = Date.now() + (job.probeTimeoutMs || 120000);',
  '  let attempts = 0;',
  '  while (Date.now() < deadline) {',
  '    const state = await inspect(job.newId);',
  '    if (state === null) { log("the new container disappeared"); return false; }',
  '    if (!state.State.Running) {',
  '      if (state.State.Status === "exited" || state.State.Status === "dead") {',
  "        log('the new container stopped (exit code ' + state.State.ExitCode + ')');",
  '        return false;',
  '      }',
  '      await sleep(1000);',
  '      continue;',
  '    }',
  '    attempts += 1;',
  '    if (await probeOnce()) {',
  "      log('probe succeeded after ' + attempts + ' attempt(s)');",
  '      return true;',
  '    }',
  "    log('probe attempt ' + attempts + ' did not succeed yet');",
  '    await sleep(2000);',
  '  }',
  "  log('probe timed out');",
  '  return false;',
  '}',
  'async function renameTo(id, target) {',
  '  await api("POST", "/containers/" + id + "/rename?name=" + encodeURIComponent(target));',
  '}',
  '// The panel has to know how a swap ended, and the container exit code alone',
  '// cannot tell "the new version is running" from "we rolled back" (both are a',
  '// concluded job, so both must exit 0 - otherwise `restart: on-failure` would',
  '// restart the helper and flap the service). The outcome is therefore written',
  '// into our own container name: -ok / -rolledback / -idle (nothing to do).',
  'async function markOutcome(suffix) {',
  '  try {',
  '    const me = await inspect(os.hostname());',
  '    if (me === null) return;',
  '    const current = nameOf(me);',
  '    if (current !== null && !current.endsWith(suffix)) {',
  '      await renameTo(me.Id, current + suffix);',
  "      log('marked this helper as ' + current + suffix);",
  '    }',
  '  } catch (e) {',
  "    log('could not mark the outcome: ' + e.message);",
  '  }',
  '}',
  'async function rollback(reason) {',
  "  log('ROLLBACK: ' + reason);",
  '  await dumpLogs(job.newId, "the replacement container");',
  '  const nw = await inspect(job.newId);',
  '  if (nw !== null && nw.State.Running) {',
  "    log('rollback: the replacement is running, stopping it first');",
  '    await api("POST", "/containers/" + job.newId + "/stop?t=15").catch(() => {});',
  '  }',
  '  try { await api("DELETE", "/containers/" + job.newId + "?force=true&v=0"); }',
  "  catch (e) { log('rollback: could not remove the new container: ' + e.message); }",
  '  const old = await inspect(job.oldId);',
  '  if (old === null) {',
  "    log('rollback: the old container does not exist any more, nothing to restore');",
  '    return;',
  '  }',
  '  if (nameOf(old) !== job.oldName) {',
  '    try { await renameTo(job.oldId, job.oldName); }',
  "    catch (e) { log('rollback: could not rename the old container back: ' + e.message); }",
  '  }',
  '  try { await api("POST", "/containers/" + job.oldId + "/start"); }',
  "  catch (e) { log('rollback: could not start the old container: ' + e.message); }",
  '}',
  'async function main() {',
  "  log('update helper (run) started, role ' + (job.role || 'primary') + ', image ' + job.image + ', replacement ' + job.newId);",
  "  log('helper identity: uid=' + (process.getuid ? process.getuid() : '?') + ' gid=' + (process.getgid ? process.getgid() : '?') + ' groups=' + (process.getgroups ? process.getgroups().join(',') : '?'));",
  '',
  '  // Fail loudly (and early) when the socket is not usable. Without this the',
  '  // first inspect() only returns null and the log blames a missing container',
  '  // instead of the real cause - usually a helper running as the image user',
  '  // without the docker socket group (0.8.0+ images run as `node`).',
  '  try {',
  '    await api("GET", "/version");',
  '  } catch (e) {',
  "    log('FATAL: the update helper cannot talk to the docker socket at ' + job.socketPath + ': ' + e.message);",
  "    log('(it needs the same socket access as the app container: same user, or the socket gid in HostConfig.GroupAdd)');",
  '    process.exit(1);',
  '  }',
  '',
  '  // The rescue helper is the second pair of eyes: the primary helper is the',
  '  // only actor while the swap is in flight, so if it dies (kill/OOM/crash)',
  '  // nothing would ever start the replacement again. The rescue waits for the',
  '  // primary to either finish or disappear, and only acts when nothing is',
  '  // serving the canonical name any more.',
  "  if (job.role === 'rescue') {",
  '    const started = Date.now();',
  '    const deadline = started + (job.rescueWaitMs || 300000);',
  '    const minWait = job.takeoverDelayMs || 8000;',
  '    while (Date.now() < deadline) {',
  '      const canonical = await inspect(job.oldName);',
  '      const peer = await inspect(job.peerName);',
  '      const peerBusy = peer !== null && (peer.State.Running || peer.State.Restarting);',
  '      if (!peerBusy && Date.now() - started >= minWait) {',
  '        if (canonical !== null && canonical.State.Running) {',
  "          log('nothing to rescue: ' + job.oldName + ' is running (id ' + String(canonical.Id).slice(0, 12) + ')');",
  "          await markOutcome('-idle');",
  '          process.exit(0);',
  '        }',
  "        log('taking over from the primary helper: nothing is running as ' + job.oldName);",
  '        break;',
  '      }',
  '      await sleep(2000);',
  '    }',
  '    const check = await inspect(job.oldName);',
  '    if (check !== null && check.State.Running) {',
  "      log('nothing to rescue (late check)');",
  "      await markOutcome('-idle');",
  '      process.exit(0);',
  '    }',
  "    log('the update did not finish, running the swap myself');",
  '  }',
  '',
  '  await sleep(job.graceMs || 1500);',
  '',
  '  // 1) move the old container out of the way (skip when a previous run did it)',
  '  let old = await inspect(job.oldId);',
  '  if (old === null) {',
  '    old = await inspect(job.oldName);',
  "    if (old !== null) log('the old container is already known as ' + nameOf(old));",
  '  }',
  '  if (old === null) {',
  "    log('the old container is gone, cannot swap anything, rolling back is not possible either');",
  '    process.exit(1);',
  '  }',
  '  // A previous run of this helper (docker restarted it) may already have',
  '  // concluded the swap - in that case touching anything again would flap the',
  '  // service. Both outcomes leave a container running under the canonical name.',
  '  if (nameOf(old) === job.oldNameAside) {',
  '    const canonical = await inspect(job.oldName);',
  '    if (canonical !== null && canonical.State.Running && canonical.Id === job.newId) {',
  "      log('an earlier run already installed the new version, nothing to do');",
  "      await markOutcome('-ok');",
  '      process.exit(0);',
  '    }',
  '    if (canonical !== null && canonical.State.Running && canonical.Id === job.oldId) {',
  "      log('an earlier run already rolled back, the previous version is running again');",
  "      await markOutcome('-rolledback');",
  '      process.exit(0);',
  '    }',
  '  }',
  '  if (nameOf(old) === job.oldNameAside) {',
  "    stage('old container already renamed aside (resumed run)');",
  '  } else {',
  '    try {',
  '      await renameTo(job.oldId, job.oldNameAside);',
  "      stage('old container renamed to ' + job.oldNameAside);",
  '    } catch (e) {',
  "      log('could not rename the old container, aborting before anything changes: ' + e.message);",
  '      process.exit(1);',
  '    }',
  '    old = await inspect(job.oldId);',
  '  }',
  '',
  '  // 2) stop it (the API inside dies here, the helper keeps running)',
  '  if (old.State.Running) {',
  '    try {',
  '      await api("POST", "/containers/" + job.oldId + "/stop?t=" + (job.stopTimeoutSec || 30));',
  "      stage('old container stopped, starting the new one');",
  '    } catch (e) {',
  "      log('could not stop the old container: ' + e.message);",
  '      if (nameOf(old) !== job.oldName) await renameTo(job.oldId, job.oldName).catch(() => {});',
  '      process.exit(1);',
  '    }',
  '  } else {',
  "    stage('old container already stopped (resumed run)');",
  '  }',
  '',
  '  // 3) put the replacement in place and start it',
  '  let nw = await inspect(job.newId);',
  '  if (nw === null) {',
  "    log('the replacement container does not exist any more');",
  '  } else if (!nw.State.Running) {',
  '    if (nameOf(nw) !== job.oldName) {',
  '      try { await renameTo(job.newId, job.oldName); }',
  "      catch (e) { log('could not rename the replacement: ' + e.message); }",
  '    }',
  '  }',
  '  let started = false;',
  '  nw = await inspect(job.newId);',
  '  if (nw !== null && nw.State.Running) {',
  "    stage('replacement already running (resumed run)');",
  '    started = true;',
  '  } else if (nw !== null) {',
  '    try {',
  '      await api("POST", "/containers/" + job.newId + "/start");',
  '      started = true;',
  '    } catch (e) {',
  "      log('could not start the new container: ' + e.message);",
  '    }',
  '  }',
  '',
  '  // 4) verify, then 5) clean up or roll back',
  '  const healthy = started ? await probeNew() : false;',
  '  if (healthy) {',
  '    try {',
  '      await api("DELETE", "/containers/" + job.oldId + "?force=true&v=0");',
  "      log('UPDATE OK: ' + job.image + ' is running as ' + job.oldName);",
  '    } catch (e) {',
  "      log('UPDATE OK, but the old container could not be removed: ' + e.message);",
  '    }',
  "    await markOutcome('-ok');",
  '    process.exit(0);',
  '  }',
  '  await rollback(started ? "new container did not become healthy" : "new container could not be started");',
  "  await markOutcome('-rolledback');",
  '  process.exit(0);',
  '}',
  'main().catch(async (e) => {',
  "  log('unexpected helper error: ' + (e && e.stack ? e.stack : String(e)));",
  '  try { await rollback("unexpected helper error"); } catch (err) { log(String(err)); }',
  "  await markOutcome('-rolledback');",
  '  process.exit(0);',
  '});',
].join('\n');
